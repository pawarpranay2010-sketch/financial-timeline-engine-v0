#!/usr/bin/env python3
"""Backend compatibility replay for the operator Pages Function signer.

Takes the fixture produced by ``scripts/operator_gateway_assertion_test.mjs``
(real Web-Crypto signatures generated by the operator function) and replays
those exact headers against the REAL backend ``require_management`` dependency
over an actual HTTP socket (uvicorn, ephemeral port), backed by a disposable
local PostgreSQL cluster. No production resource is contacted.

Proves, end to end:
  * all eight management endpoints accept a JS-signed assertion
  * the canonical message, delimiter, header names, trimmed secret, tenant,
    empty-query header transport and empty-body hash all agree
  * altering method / path / query / content-type / body breaks acceptance
  * replaying one signed request twice hits nonce replay protection

Usage: python3 scripts/operator_gateway_backend_compat_test.py
Env:   OPERATOR_ASSERTION_FIXTURE (default /tmp/operator_assertion_fixture.json)
"""

from __future__ import annotations

import base64
import json
import os
import pathlib
import socket
import sys
import threading
import time

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
FIXTURE_PATH = pathlib.Path(
    os.environ.get("OPERATOR_ASSERTION_FIXTURE", "/tmp/operator_assertion_fixture.json")
)

RESULTS: list[tuple[str, bool, str]] = []


def check(name: str, condition: bool, detail: str = "") -> None:
    RESULTS.append((name, bool(condition), detail))
    status = "PASS" if condition else "FAIL"
    print(f"  [{status}] {name}" + (f" — {detail}" if detail and not condition else ""))


def _free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def main() -> int:
    if not FIXTURE_PATH.exists():
        raise SystemExit(
            f"fixture missing: {FIXTURE_PATH} — run node scripts/operator_gateway_assertion_test.mjs first"
        )
    fixture = json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))

    # --- disposable PostgreSQL -------------------------------------------
    import pgserver

    server = pgserver.get_server("/tmp/op_compat_pg", cleanup_mode=None)
    server.psql("DROP DATABASE IF EXISTS op_compat;")
    server.psql("CREATE DATABASE op_compat;")
    uri = server.get_uri().replace("/postgres?", "/op_compat?")
    print(f"disposable postgres: op_compat ({'/tmp/op_compat_pg'})")

    os.environ.update(
        {
            "DATABASE_URL": uri,
            "PLATRIXA_METERING_DATABASE_URL": uri,
            "PLATRIXA_KEY_MANAGEMENT_TOKEN": fixture["token"],
            "PLATRIXA_KEY_MANAGEMENT_TENANT_ID": fixture["tenant"],
            "PLATRIXA_MANAGEMENT_ASSERTION_SECRET": fixture["secret"],
            "PLATRIXA_MANAGEMENT_TRUSTED_ISSUERS": fixture["issuer"],
        }
    )

    from sqlalchemy import create_engine, text

    engine = create_engine(uri.replace("postgresql://", "postgresql+psycopg2://", 1), future=True)
    quota_ddl = (ROOT / "backend" / "database" / "platrixa_tenant_quota_schema.sql").read_text(
        encoding="utf-8"
    )
    with engine.begin() as conn:
        conn.execute(text(quota_ddl))

    from api.main import create_app

    app = create_app()

    # --- real HTTP hop via uvicorn on an ephemeral loopback port ---------
    import uvicorn

    port = _free_port()
    config = uvicorn.Config(app, host="127.0.0.1", port=port, log_level="error", lifespan="off")
    uv_server = uvicorn.Server(config)
    thread = threading.Thread(target=uv_server.run, daemon=True)
    thread.start()

    deadline = time.time() + 20
    while time.time() < deadline:
        try:
            with socket.create_connection(("127.0.0.1", port), timeout=0.5):
                break
        except OSError:
            time.sleep(0.05)
    else:
        raise SystemExit("uvicorn did not start")

    import httpx

    base = f"http://127.0.0.1:{port}"
    expected = {
        "create key": 201,
        "list keys": 200,
        "revoke key": 404,
        "rotate key": 404,
        "key usage": 404,
        "tenant usage": 200,
        "request list": 200,
        "request detail": 404,
    }

    try:
        with httpx.Client(base_url=base, timeout=30.0) as client:
            print("\n--- eight management endpoints with JS-signed assertions ---")
            for entry in fixture["requests"]:
                headers = dict(entry["headers"])
                body = base64.b64decode(entry["body_b64"])
                method = entry["method"]
                response = client.request(
                    method,
                    entry["path_with_query"],
                    headers=headers,
                    content=body if method not in ("GET", "HEAD") else None,
                )
                want = expected.get(entry["name"])
                check(
                    f"{entry['name']}: {method} {entry['path_with_query']} → {want}",
                    response.status_code == want,
                    f"{response.status_code} {response.text[:400]}",
                )

            print("\n--- altered transport must be rejected (403) ---")
            for entry in fixture.get("tamper_requests", []):
                headers = dict(entry["headers"])
                headers.update(entry.get("send_headers") or {})
                method = entry.get("send_method", entry["method"])
                path = entry.get("send_path_with_query", entry["path_with_query"])
                body = base64.b64decode(
                    entry.get("send_body_b64", entry["body_b64"])
                )
                response = client.request(
                    method,
                    path,
                    headers=headers,
                    content=body if method not in ("GET", "HEAD") else None,
                )
                check(
                    f"rejected: {entry['name']} → 403",
                    response.status_code == 403,
                    f"{response.status_code} {response.text[:400]}",
                )

            print("\n--- replay of one signed request ---")
            replay = fixture.get("replay_request")
            if replay:
                headers = dict(replay["headers"])
                first = client.request(replay["method"], replay["path_with_query"], headers=headers)
                second = client.request(replay["method"], replay["path_with_query"], headers=headers)
                check("first send accepted", first.status_code == 200, str(first.status_code))
                check(
                    "second send rejected by nonce replay protection (403)",
                    second.status_code == 403,
                    str(second.status_code),
                )
    finally:
        uv_server.should_exit = True
        thread.join(timeout=10)
        try:
            server.cleanup()  # type: ignore[attr-defined]
        except Exception:
            pass

    failed = [result for result in RESULTS if not result[1]]
    print(f"\n{len(RESULTS) - len(failed)}/{len(RESULTS)} backend compatibility checks passed")
    return 0 if not failed else 1


if __name__ == "__main__":
    sys.exit(main())
