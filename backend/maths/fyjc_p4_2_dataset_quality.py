"""
P4.2 — Specialist AI Dataset Quality, Target Restructuring & Training Readiness
================================================================================

Builds trustworthy labelled training data for the specialist finance AI.
The kernel remains the authority. The AI learns language understanding only.

Key principle:
  SPECIALIST AI = understand language → produce grounded structured interpretation
  TRUTH KERNEL  = calculate, apply accounting rules, verify and establish truth
"""

from __future__ import annotations

import json
import os
import re
import hashlib
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from decimal import Decimal, InvalidOperation
from typing import Any, Dict, List, Optional, Tuple


