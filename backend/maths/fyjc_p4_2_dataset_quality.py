# Vocabulary maps for transaction-type detection
PURCHASE_WORDS = {
    "purchased", "bought", "procured", "acquired", "obtained",
    "brought", "got", "received goods", "taken",
}
SALE_WORDS = {
    "sold", "sold goods", "sales", "supplied", "delivered",
    "sold on credit", "sold for cash",
}
EXPENSE_WORDS = {
    "paid rent", "paid salary", "paid electricity", "paid wages",
    "paid carriage", "paid telephone", "paid insurance", "paid stationery",
    "paid for", "payment of", "paid",
}
SETTLEMENT_WORDS = {
    "settled", "settlement", "full settlement", "paid in full",
    "cleared account", "account settled", "paid off",
}
RETURN_WORDS = {
    "returned", "return", "goods returned", "purchase return",
    "sales return", "returned goods",
}

# Payment method detection
CASH_WORDS = {"cash", "by cash", "for cash", "in cash", "paid cash"}
CHEQUE_WORDS = {"cheque", "by cheque", "cheque no", "cheque number"}
NEFT_WORDS = {"neft", "rtgs", "imps", "bank transfer", "online transfer", "upi"}
CREDIT_WORDS = {"credit", "on credit", "on account", "credit purchase", "credit sale"}

# Amount extraction patterns
AMOUNT_PATTERNS = [
    r"Rs\.?\s*([\d,]+(?:\.\d{1,2})?)",
    r"INR\s*([\d,]+(?:\.\d{1,2})?)",
    r"₹\s*([\d,]+(?:\.\d{1,2})?)",
    r"rupees?\s*([\d,]+(?:\.\d{1,2})?)",
]


def _extract_parties(text: str) -> List[str]:
    """Extract party names from student input text."""
    parties = []

    # Pattern: "from <Name>" or "to <Name>"
    for pattern in [r"from\s+([A-Z][a-zA-Z\s&.]+?)(?:\s+for|\s+Rs|\s+on|\s+worth|\s*,|\s*\.)", r"to\s+([A-Z][a-zA-Z\s&.]+?)(?:\s+for|\s+Rs|\s+on|\s+worth|\s*,|\s*\.)"]:
        for m in re.finditer(pattern, text, re.IGNORECASE):
            name = m.group(1).strip()
            # Clean up: remove trailing prepositions
            name = re.sub(r"\s+(for|Rs|on|worth|by|and)\s*$", "", name, flags=re.IGNORECASE).strip()
            if len(name) > 1 and name.lower() not in {"goods", "cash", "bank", "the", "some", "all"}:
                parties.append(name)

    # Deduplicate preserving order
    seen = set()
    unique = []
    for p in parties:
        canonical = p.lower().strip()
        if canonical not in seen:
            seen.add(canonical)
            unique.append(p)
    return unique


def _extract_amounts(text: str) -> List[Dict[str, str]]:
    """Extract explicit monetary amounts from student input text."""
    amounts = []
    for pattern in AMOUNT_PATTERNS:
        for m in re.finditer(pattern, text, re.IGNORECASE):
            raw = m.group(1).replace(",", "")
            try:
                value = str(Decimal(raw))
                amounts.append({"value": value, "currency": "INR", "source": "explicit"})
            except InvalidOperation:
                pass

    # Deduplicate by value
    seen = set()
    unique = []
    for a in amounts:
        if a["value"] not in seen:
            seen.add(a["value"])
            unique.append(a)
    return unique


def _detect_payment_method(text: str) -> str:
    """Detect payment method from student input."""
    lower = text.lower()
    for w in CHEQUE_WORDS:
        if w in lower:
            return "cheque"
    for w in NEFT_WORDS:
        if w in lower:
            return "bank_transfer"
    for w in CASH_WORDS:
        if w in lower:
            return "cash"
    for w in CREDIT_WORDS:
        if w in lower:
            return "credit"
    return ""


def _detect_transaction_type(text: str, debit_accounts: List[Dict], credit_accounts: List[Dict]) -> str:
    """Detect transaction type from input text and journal accounts."""
    lower = text.lower()

    # Check explicit keywords first
    for w in RETURN_WORDS:
        if w in lower:
            return "return"
    for w in SETTLEMENT_WORDS:
        if w in lower:
            return "settlement"

    # Check debit/credit account names for classification
    debit_names = " ".join(da.get("account", "").lower() for da in (debit_accounts or []))
    credit_names = " ".join(ca.get("account", "").lower() for ca in (credit_accounts or []))

    if "purchases" in debit_names or "purchase" in debit_names:
        return "purchase"
    if "sales" in credit_names or "sale" in credit_names:
        return "sale"
    if "capital" in credit_names:
        return "capital_introduction"
    if any(x in debit_names for x in ["rent", "salary", "wages", "electricity", "telephone", "carriage", "stationery", "insurance", "furniture"]):
        return "expense"

    # Fallback: keyword detection
    for w in PURCHASE_WORDS:
        if w in lower:
            return "purchase"
    for w in SALE_WORDS:
        if w in lower:
            return "sale"
    for w in EXPENSE_WORDS:
        if w in lower:
            return "expense"

    return "unknown"


def _detect_ambiguities(text: str, status: str) -> List[str]:
    """Detect ambiguities in the student input."""
    ambiguities = []
    lower = text.lower()

    # Payment mode missing
    has_payment = any(w in lower for w in ["cash", "credit", "cheque", "neft", "rtgs", "upi", "bank transfer"])
    if not has_payment and "paid" not in lower:
        ambiguities.append("payment_method_ambiguous")

    # Fraction/relative amounts
    if re.search(r"\b(half|third|quarter|percent|some|part|remaining)\b", lower):
        ambiguities.append("relative_amount")

    # Pronouns without clear antecedent
    if re.search(r"\b(he|she|they|them|his|her|its)\b", lower, re.IGNORECASE):
        ambiguities.append("pronoun_reference")

    # Settlement without explicit amount
    if "settlement" in lower or "settled" in lower:
        if not re.search(r"Rs\.?|₹|INR|rupees", lower):
            ambiguities.append("settlement_amount_ambiguous")

    return ambiguities


def _detect_references(text: str) -> List[str]:
    """Detect cross-transaction references."""
    refs = []
    lower = text.lower()
    if re.search(r"\b(previous|last|above|earlier|first|second|third)\b.*(balance|transaction|entry|amount)", lower):
        refs.append("historical_reference")
    if re.search(r"\b(he|she|they|them|his|her)\b", lower, re.IGNORECASE):
        refs.append("pronoun_reference")
    if re.search(r"\b(remaining|balance|outstanding|left|due)\b", lower):
        refs.append("balance_reference")
    return refs


def label_record(case: Dict[str, Any]) -> StructuredInterpretation:
    """Produce a deterministic structured interpretation for a candidate case.

    Uses the INPUT TEXT (what the student wrote) and JOURNAL RESULTS (kernel output)
    to build the interpretation target. This is NOT the kernel's journal — it is
    the language-understanding layer's target.
    """
    input_text = case.get("input_text", "")
    status = case.get("status", "")
    debit_accounts = case.get("debit_accounts", []) or []
    credit_accounts = case.get("credit_accounts", []) or []
    journal_narration = case.get("journal_narration", "")
    category = case.get("category", "")

    parties = _extract_parties(input_text)
    amounts = _extract_amounts(input_text)
    payment_method = _detect_payment_method(input_text)
    transaction_type = _detect_transaction_type(input_text, debit_accounts, credit_accounts)
    ambiguities = _detect_ambiguities(input_text, status)
    references = _detect_references(input_text)

    # Grounding: all fields are explicitly present in the input text
    inferred_fields = []
    if not payment_method and status == "VERIFIED":
        # Payment method was inferred by kernel (not stated by student)
        # Check if journal implies cash
        credit_names = " ".join(ca.get("account", "").lower() for ca in credit_accounts)
        if "cash" in credit_names:
            payment_method = "cash_inferred"
            inferred_fields.append("payment_method")
        elif credit_names and credit_names != "cash":
            payment_method = "credit_inferred"
            inferred_fields.append("payment_method")

    grounding = {
        "all_fields_explicitly_grounded": len(inferred_fields) == 0,
        "inferred_fields": inferred_fields,
    }

    return StructuredInterpretation(
        transaction_type=transaction_type,
        parties=parties,
        amounts=amounts,
        payment_method=payment_method,
        references=references,
        ambiguities=ambiguities,
        grounding=grounding,
    )


