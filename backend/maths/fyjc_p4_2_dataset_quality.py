# Evaluation Report
# ---------------------------------------------------------------------------

def generate_evaluation_report(
    cases: List[Dict[str, Any]],
    tiers: Dict[str, DatasetTier],
) -> Dict[str, Any]:
    """Generate the P4.2 evaluation report."""
    audit = audit_dataset(cases)

    # Per-category stats for VERIFIED
    verified = [c for c in cases if c.get("status") == "VERIFIED"]
    categories = Counter(c.get("category", "other") for c in verified)

    # Field accuracy for VERIFIED (after labeling)
    field_accuracy = {}
    for field_name in ["transaction_type", "parties", "amounts", "payment_method"]:
        count = 0
        for c in verified:
            interp = label_record(c)
            val = getattr(interp, field_name, None)
            if val and val != "unknown" and val != "":
                count += 1
        field_accuracy[field_name] = f"{count}/{len(verified)} ({count/len(verified)*100:.1f}%)" if verified else "N/A"

    # Tier sizes
    tier_sizes = {k: len(v.records) for k, v in tiers.items()}

    # Cross-tier overlap check
    train_ids = {r["_p4_metadata"]["problem_id"] for r in tiers["specialist_clean_training"].records}
    eval_ids = set()
    for k in ["specialist_ambiguity_eval", "specialist_unsupported_eval", "specialist_robustness_eval"]:
        eval_ids |= {r["_p4_metadata"]["problem_id"] for r in tiers[k].records}
    overlap = check_train_eval_overlap(train_ids, eval_ids)

    return {
        "audit": {
            "total": audit.total,
            "verified": audit.verified,
            "review_required": audit.review_required,
            "not_supported": audit.not_supported,
            "blocked": audit.blocked,
            "exception": audit.exception,
        },
        "field_population": {
            "transaction_type": audit.verified_with_transaction_type,
            "parties": audit.verified_with_parties,
            "amounts": audit.verified_with_amounts,
            "payment_method": audit.verified_with_payment_method,
            "references": audit.verified_with_references,
            "ambiguities": audit.verified_with_ambiguities,
            "substantive_interpretation": audit.verified_with_substantive_interpretation,
        },
        "field_accuracy": field_accuracy,
        "empty_field_classification": {
            "upstream_labeling_gap": audit.upstream_labeling_gap,
            "genuinely_absent": audit.genuinely_absent,
        },
        "training_floor": {
            "required": 40,
            "usable_verified": audit.usable_verified,
            "met": audit.training_floor_met,
            "shortfall": audit.training_floor缺口,
        },
        "tier_sizes": tier_sizes,
        "train_eval_overlap": overlap,
        "categories_in_verified": dict(categories),
        "duplicates": audit.duplicate_problem_ids,
    }
