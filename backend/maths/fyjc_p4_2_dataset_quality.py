@dataclass
class DatasetTier:
    name: str
    instruction: str
    records: List[Dict[str, Any]] = field(default_factory=list)


def build_four_tiers(cases: List[Dict[str, Any]]) -> Dict[str, DatasetTier]:
    """Build four data tiers from the candidate corpus.

    Tier 1: specialist_clean_training.jsonl  — usable VERIFIED only
    Tier 2: specialist_ambiguity_eval.jsonl  — REVIEW_REQUIRED
    Tier 3: specialist_unsupported_eval.jsonl — NOT_SUPPORTED
    Tier 4: specialist_robustness_eval.jsonl  — BLOCKED + EXCEPTION
    """
    tiers = {
        "specialist_clean_training": DatasetTier(
            name="specialist_clean_training",
            instruction=INSTRUCTION_CLEAN,
        ),
        "specialist_ambiguity_eval": DatasetTier(
            name="specialist_ambiguity_eval",
            instruction=INSTRUCTION_AMBIGUITY,
        ),
        "specialist_unsupported_eval": DatasetTier(
            name="specialist_unsupported_eval",
            instruction=INSTRUCTION_UNSUPPORTED,
        ),
        "specialist_robustness_eval": DatasetTier(
            name="specialist_robustness_eval",
            instruction=INSTRUCTION_SAFETY,
        ),
    }

    for case in cases:
        status = case.get("status", "UNKNOWN")
        interp = label_record(case)

        # Build the output string (structured interpretation only, NO journal)
        output_dict = interp.to_dict()
        output_string = json.dumps(output_dict, ensure_ascii=False, default=str)

        # Determine content hash for dedup
        input_text = case.get("input_text", "")
        content_hash = hashlib.sha256(
            f"{input_text}:{output_string}".encode("utf-8")
        ).hexdigest()[:12]

        record = {
            "instruction": "",
            "input": input_text,
            "output": output_string,
            "_p4_metadata": {
                "problem_id": case.get("case_id", ""),
                "category": case.get("category", ""),
                "subcategory": case.get("subcategory", ""),
                "engine_status": status,
                "content_hash": content_hash,
            },
        }

        if status == "VERIFIED":
            # Only include if has substantive interpretation
            if not interp.is_substantially_empty():
                record["instruction"] = tiers["specialist_clean_training"].instruction
                tiers["specialist_clean_training"].records.append(record)
        elif status == "REVIEW_REQUIRED":
            record["instruction"] = tiers["specialist_ambiguity_eval"].instruction
            tiers["specialist_ambiguity_eval"].records.append(record)
        elif status == "NOT_SUPPORTED":
            record["instruction"] = tiers["specialist_unsupported_eval"].instruction
            tiers["specialist_unsupported_eval"].records.append(record)
        elif status in ("BLOCKED", "EXCEPTION"):
            record["instruction"] = tiers["specialist_robustness_eval"].instruction
            tiers["specialist_robustness_eval"].records.append(record)

    # Deterministic ordering by content_hash
    for tier in tiers.values():
        tier.records.sort(key=lambda r: r["_p4_metadata"]["content_hash"])

    return tiers


