# Quality Validation
# ---------------------------------------------------------------------------

def validate_record(record: Dict[str, Any]) -> Tuple[bool, str]:
    """Validate a single training record.

    Returns (is_valid, reason_if_invalid).
    """
    # Required fields
    for key in ("instruction", "input", "output"):
        if key not in record or not record[key]:
            return False, f"missing_required_field:{key}"

    # Output must be valid JSON
    try:
        output = json.loads(record["output"])
    except (json.JSONDecodeError, TypeError):
        return False, "output_not_valid_json"

    # Must have transaction_type
    if not output.get("transaction_type"):
        return False, "missing_transaction_type"

    # Must have parties (at least for clean training)
    if not output.get("parties"):
        return False, "missing_parties"

    # Must have amounts
    if not output.get("amounts"):
        return False, "missing_amounts"

    # No fabricated entities: parties must appear in input
    input_lower = record["input"].lower()
    for party in output.get("parties", []):
        if party.lower() not in input_lower:
            return False, f"fabricated_party:{party}"

    # No fabricated amounts: amounts must appear in input
    for amt in output.get("amounts", []):
        value = amt.get("value", "")
        if value and value not in record["input"] and value.replace(".", "") not in record["input"]:
            # Check if amount was inferred from journal (allowed but must be flagged)
            grounding = output.get("grounding", {})
            if not grounding.get("inferred_fields"):
                return False, f"fabricated_amount:{value}"

    # Unique problem_id
    problem_id = record.get("_p4_metadata", {}).get("problem_id", "")
    if not problem_id:
        return False, "missing_problem_id"

    return True, "ok"


def validate_dataset(records: List[Dict[str, Any]], tier_name: str) -> Dict[str, Any]:
    """Validate an entire dataset tier."""
    results = {
        "tier": tier_name,
        "total": len(records),
        "valid": 0,
        "invalid": 0,
        "rejected": [],
        "problem_ids": set(),
        "duplicates": 0,
    }

    for rec in records:
        is_valid, reason = validate_record(rec)
        pid = rec.get("_p4_metadata", {}).get("problem_id", "")

        if pid in results["problem_ids"]:
            results["duplicates"] += 1
            is_valid = False
            reason = "duplicate_problem_id"

        results["problem_ids"].add(pid)

        if is_valid:
            results["valid"] += 1
        else:
            results["invalid"] += 1
            results["rejected"].append({"problem_id": pid, "reason": reason})

    results["problem_ids"] = len(results["problem_ids"])
    return results


def check_train_eval_overlap(
    train_ids: set, eval_ids: set
) -> int:
    """Check for overlap between training and evaluation sets."""
    return len(train_ids & eval_ids)


# ---------------------------------------------------------------------------
# Export Tiers
# ---------------------------------------------------------------------------

def export_tiers(
    tiers: Dict[str, DatasetTier],
    output_dir: str = "training_data",
) -> Dict[str, Dict[str, Any]]:
    """Export all four tiers to JSONL files with validation."""
    os.makedirs(output_dir, exist_ok=True)
    results = {}

    for key, tier in tiers.items():
        output_path = os.path.join(output_dir, f"{key}.jsonl")
        with open(output_path, "w", encoding="utf-8") as f:
            for rec in tier.records:
                f.write(json.dumps(rec, ensure_ascii=False, default=str) + "\n")

        validation = validate_dataset(tier.records, key)
        results[key] = validation

    return results


