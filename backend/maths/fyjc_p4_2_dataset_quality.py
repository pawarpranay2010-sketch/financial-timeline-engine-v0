@dataclass
class StructuredInterpretation:
    """The canonical specialist-AI target.

    This represents WHAT THE STUDENT MEANT / WHAT IS EXPLICITLY PRESENT.
    It must NOT represent the journal generated by the kernel.
    """
    transaction_type: str = ""
    parties: List[str] = field(default_factory=list)
    amounts: List[Dict[str, str]] = field(default_factory=list)
    payment_method: str = ""
    references: List[str] = field(default_factory=list)
    ambiguities: List[str] = field(default_factory=list)
    grounding: Dict[str, Any] = field(default_factory=lambda: {
        "all_fields_explicitly_grounded": True,
        "inferred_fields": [],
    })

    def to_dict(self) -> Dict[str, Any]:
        return {
            "transaction_type": self.transaction_type,
            "parties": self.parties,
            "amounts": self.amounts,
            "payment_method": self.payment_method,
            "references": self.references,
            "ambiguities": self.ambiguities,
            "grounding": self.grounding,
        }

    def to_json_string(self) -> str:
        return json.dumps(self.to_dict(), ensure_ascii=False, default=str)

    def is_substantially_empty(self) -> bool:
        return (
            not self.transaction_type
            and not self.parties
            and not self.amounts
            and not self.payment_method
        )


