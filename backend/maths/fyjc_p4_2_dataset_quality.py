INSTRUCTION_CLEAN = (
    "Parse the student's accounting language into a grounded structured "
    "interpretation. Do not invent missing information. Identify: "
    "transaction_type, parties, amounts, payment_method, references, "
    "ambiguities, and grounding status."
)

INSTRUCTION_AMBIGUITY = (
    "The following accounting transaction is ambiguous. Identify what is "
    "ambiguous, what information is missing, and what clarification "
    "question should be asked."
)

INSTRUCTION_UNSUPPORTED = (
    "The following transaction is outside the supported FYJC Book-Keeping "
    "syllabus. Classify why it is unsupported and what the student likely "
    "intended."
)

INSTRUCTION_SAFETY = (
    "The following input is blocked or caused an error. Classify why it "
    "was blocked and what safety invariant was violated."
)


@dataclass
class DatasetAudit:
    """Audit results for the candidate corpus."""
    total: int = 0
    verified: int = 0
    review_required: int = 0
    not_supported: int = 0
    blocked: int = 0
    exception: int = 0

    # Field population (VERIFIED only)
    verified_with_transaction_type: int = 0
    verified_with_parties: int = 0
    verified_with_amounts: int = 0
    verified_with_payment_method: int = 0
    verified_with_references: int = 0
    verified_with_ambiguities: int = 0
    verified_with_substantive_interpretation: int = 0

    # Classification of empty fields
    upstream_labeling_gap: int = 0
    genuinely_absent: int = 0

    # Duplicates
    duplicate_problem_ids: int = 0
    unique_problem_ids: int = 0

    # Training floor
    usable_verified: int = 0
    training_floor_met: bool = False
    training_floor缺口: int = 0


def audit_dataset(cases: List[Dict[str, Any]]) -> DatasetAudit:
    """Audit the candidate corpus and classify empty fields."""
    audit = DatasetAudit()
    audit.total = len(cases)

    # Status counts
    for c in cases:
        s = c.get("status", "UNKNOWN")
        if s == "VERIFIED":
            audit.verified += 1
        elif s == "REVIEW_REQUIRED":
            audit.review_required += 1
        elif s == "NOT_SUPPORTED":
            audit.not_supported += 1
        elif s == "BLOCKED":
            audit.blocked += 1
        elif s == "EXCEPTION":
            audit.exception += 1

    # Duplicate check
    problem_ids = [c.get("case_id", "") for c in cases]
    audit.unique_problem_ids = len(set(problem_ids))
    audit.duplicate_problem_ids = len(problem_ids) - audit.unique_problem_ids

    # Field population for VERIFIED records
    verified_cases = [c for c in cases if c.get("status") == "VERIFIED"]
    for c in verified_cases:
        interp = label_record(c)
        if interp.transaction_type and interp.transaction_type != "unknown":
            audit.verified_with_transaction_type += 1
        if interp.parties:
            audit.verified_with_parties += 1
        if interp.amounts:
            audit.verified_with_amounts += 1
        if interp.payment_method:
            audit.verified_with_payment_method += 1
        if interp.references:
            audit.verified_with_references += 1
        if interp.ambiguities:
            audit.verified_with_ambiguities += 1
        if not interp.is_substantially_empty():
            audit.verified_with_substantive_interpretation += 1

    # Classify empty fields
    for c in verified_cases:
        input_text = c.get("input_text", "")
        interp = label_record(c)

        # Check if information is genuinely absent from student input
        has_amount_in_text = bool(re.search(r"Rs\.?|₹|INR|rupees", input_text, re.IGNORECASE))
        has_party_in_text = bool(re.search(r"from\s+[A-Z]|to\s+[A-Z]", input_text))
        has_payment_in_text = any(w in input_text.lower() for w in ["cash", "credit", "cheque", "neft"])

        if not has_amount_in_text:
            audit.genuinely_absent += 1
        elif not interp.parties and has_party_in_text:
            audit.upstream_labeling_gap += 1
        elif not interp.payment_method and not has_payment_in_text:
            # Payment mode is genuinely absent — this is the ambiguity case
            audit.genuinely_absent += 1

    # Training floor: 40 usable VERIFIED examples
    # Usable = has substantive interpretation (not all-null)
    audit.usable_verified = audit.verified_with_substantive_interpretation
    audit.training_floor_met = audit.usable_verified >= 40
    audit.training_floor缺口 = max(0, 40 - audit.usable_verified)

    return audit


